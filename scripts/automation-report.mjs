// Writes docs/AUTOMATION.md: every feature the sheet doesn't fully automate.
// Run: node scripts/automation-report.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..", "src", "data", "content");
const files = [];
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (f.endsWith(".json")) files.push(p);
  }
};
walk(root);

const rows = [];
for (const file of files) {
  const data = JSON.parse(readFileSync(file, "utf8"));
  const entries = Array.isArray(data) ? data : [data];
  for (const e of entries) {
    const feats = [...(e.features ?? []), ...Object.values(e.optionPools ?? {}).flat()];
    for (const f of feats) {
      if (!f.automation || f.automation === "full") continue;
      rows.push({ owner: e.name ?? e.id, name: f.name, how: f.automation, note: (f.manualNote ?? "").replace(/\|/g, "/").replace(/\n/g, " "), page: `${f.source.file.replace(".pdf", "")} p.${f.source.printedPage}` });
    }
  }
}
rows.sort((a, b) => a.owner.localeCompare(b.owner) || a.name.localeCompare(b.name));

const out = [
  "# Automation report",
  "",
  "Features the sheet does not fully automate. They always show their full text on the Features tab, with manual controls (resources, uses, toggles, notes). Generated by `node scripts/automation-report.mjs` from the content data; don't edit by hand.",
  "",
  "Also by hand everywhere: anything about other creatures or the map (targets' conditions, distances, who is Distracted), the GM's monsters, and effects on other players' rolls.",
  "",
  `| From | Feature | Level of automation | What the player does | Source |`,
  `|---|---|---|---|---|`,
  ...rows.map((r) => `| ${r.owner} | ${r.name} | ${r.how === "manual" ? "By hand" : "Partly"} | ${r.note || "See feature text."} | ${r.page} |`),
  "",
  `${rows.length} features listed.`,
  "",
];
writeFileSync(join(import.meta.dirname, "..", "docs", "AUTOMATION.md"), out.join("\n"));
console.log(`docs/AUTOMATION.md: ${rows.length} features`);
